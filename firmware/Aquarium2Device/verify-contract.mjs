// Static offline checks only. Does not execute firmware or contact Firebase.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('./Aquarium2Device.ino', import.meta.url), 'utf8');
const config = fs.readFileSync(new URL('./Config.h', import.meta.url), 'utf8');
const feeder = fs.readFileSync(new URL('./FeederConfig.h', import.meta.url), 'utf8');
assert.match(feeder, /FEEDER_HOLD_MS = 1500/);
assert.match(feeder, /FEEDER_COOLDOWN_MS = 5000/);
assert.match(feeder, /FEEDER_HOME_DEG = 135/);
assert.match(feeder, /FEEDER_DISPENSE_DEG = 45/);
assert.match(feeder, /owner-confirmed SG90/);
assert.match(source, /if \(!ledcAttach\(SERVO_PIN, 50, 16\)\)/);
assert.match(source, /if \(!ledcWrite\(SERVO_PIN, duty\)\)/);
assert.match(source, /actualHz == 50 && actualDuty == duty/);
assert.match(source, /LIGHT_PIN = 16, FILTER_PIN = 17, SERVO_PIN = 23/);
assert.match(source, /type == "feed_now"/);
assert.match(source, /bool runManualFeed\(\)/);
assert.match(source, /millis\(\) - holdStart < FEEDER_HOLD_MS/);
assert.match(source, /millis\(\) - lastFeedEnd < FEEDER_COOLDOWN_MS/);
assert.match(source, /ledcDetach\(SERVO_PIN\)/);
assert.match(source, /stopFeederPwm\(\)/);
const setup = source.slice(source.indexOf('void setup()'), source.indexOf('void loop()'));
assert.ok(!setup.includes('ledcAttach') && !setup.includes('writeFeederPosition'), 'No automatic servo movement at boot');
const rules = JSON.parse(fs.readFileSync(new URL('../../database.rules.json', import.meta.url), 'utf8'));
const fields = [...source.matchAll(/telemetry\["([^"]+)"\]/g)].map(match => match[1]);
const schema = rules.rules.devices.$aquariumId.telemetry;
for (const field of fields) assert.ok(schema[field], `Unsupported telemetry field: ${field}`);
for (const field of ['temperatureC', 'waterLevelPercent', 'mainsPresent', 'online', 'updatedAt'])
  assert.ok(fields.includes(field), `Missing required field: ${field}`);
assert.match(config, /#define AQUARIUM_TDS_METER_REFERENCE_ENABLED 1/);
assert.match(config, /POWER_SENSOR_ANALOG = false/);
assert.match(config, /POWER_SIGNAL_ON_V = 0\.0f/);
assert.match(source, /#define AQUARIUM_TDS_METER_REFERENCE_ENABLED 0/);
assert.match(source, /if \(!TDS_METER_REFERENCE_ENABLED/);
assert.ok(!fields.includes('tdsPercent'), 'A ppm comparison is not a water-purity percentage');
assert.ok(!fields.includes('turbidity'), 'Categorical sample must not be encoded as numeric turbidity');
assert.ok(source.includes('esp_crt_bundle_attach'));
assert.match(source, /config\.buffer_size_tx = int\(url\.length\(\) \+ 512\)/);
assert.match(source, /if \(url\.length\(\) > 7680\) return -1/);
assert.ok(!source.includes('.setInsecure('));
assert.match(config, /#define AQUARIUM_CLOUD_ENABLED 1/);
assert.match(config, /#include "DeviceIdentity\.h"/);
assert.match(config, /aquarium2-firmware-secrets\.h/);
assert.doesNotMatch(config, /aquarium1-firmware-secrets|SAQ-7K3M-9R2X/);
assert.match(source, /scheduleStore\.begin\("aq2-schedule"/);
assert.match(source, /armed = !localStop/);
assert.match(source, /commandWatermarkMs = double\(time\(nullptr\)\) \* 1000.0/);
assert.match(source, /requestedMs <= commandWatermarkMs/);
assert.match(source, /database\("commandAck\/latest", HTTP_METHOD_PUT, payload, response\)/);
assert.match(source, /acknowledgement\["executedAt"\]\["\.sv"\] = "timestamp"/);
assert.match(source, /writeCommandAck\(commandId, completed, failure, "app"/);
assert.match(source, /const bool relayStateValid = \(type == "set_light_state"/);
assert.match(source, /relayStateValid \? state : String\(\)/);
assert.match(source, /writeCommandAck\(scheduleCommandId\("feed_now", minute\), completed/);
assert.match(source, /scheduleCommandId\("set_light_state", lightBoundary\)/);
assert.match(source, /scheduleCommandId\("set_filter_state", filterBoundary\)/);
assert.match(source, /commandId\.length\(\) > 160/);
assert.match(config, /POWER_PRESENT_LEVEL = 0/);
assert.match(source, /telemetry\["powerStatus"\] = PowerSignal::label\(reportedPower\)/);
assert.match(source, /if \(reportedPower != PowerSignal::State::Unknown\)\s*telemetry\["mainsPresent"\] = reportedPower == PowerSignal::State::Present/);
assert.match(source, /POWER_PIN = 33/);
assert.match(source, /LIGHT_PIN = 16, FILTER_PIN = 17/);
assert.match(source, /bus18\(18\), bus19\(19\)/);
console.log('Static contract checks passed: pins, defaults, TLS, telemetry schema, and app/schedule acknowledgements.');
