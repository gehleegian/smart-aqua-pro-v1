import type { Firestore } from 'firebase-admin/firestore';

/**
 * FR17/FR19 command log (Sprint 4). RTDB holds only the latest command and
 * the latest acknowledgement (devices/{id}/commands/latest, commandAck/latest);
 * these functions keep the history in Firestore `command_logs`, written only
 * by Cloud Functions and readable by the tank's members (Firestore rules).
 *
 *   command written  -> pending
 *   ack done/failed  -> done | failed (executedAt, error)
 *   no ack in 30 s   -> no_response (scheduled check); a late ack still wins
 *   ack with source 'schedule' and no matching command -> a schedule entry
 *
 * Doc id: `${aquariumId}_${commandId}`. commandId is generated by the client,
 * so the aquarium prefix keeps two tanks from ever sharing a log entry.
 */
export const COMMAND_NO_RESPONSE_MS = 30_000;
const COMMAND_TYPES = new Set(['feed_now', 'set_filter_state', 'set_light_state', 'sync_control']);
const STATES = new Set(['Active', 'Inactive', 'On', 'Off']);
const ID_PATTERN = /^[A-Za-z0-9_.:-]{1,160}$/;

export type CommandStatus = 'pending' | 'done' | 'failed' | 'no_response';

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

export function commandLogId(aquariumId: string, commandId: string) {
  return `${aquariumId}_${commandId}`;
}

async function displayName(firestore: Firestore, uid: string) {
  const profile = await firestore.doc(`users/${uid}`).get();
  return (profile.get('name') as string | undefined) ?? (profile.get('full_name') as string | undefined) ?? null;
}

async function aquariumOrg(firestore: Firestore, aquariumId: string) {
  const aquarium = await firestore.doc(`aquariums/${aquariumId}`).get();
  return aquarium.exists ? ((aquarium.get('orgId') as string | undefined) ?? null) : undefined;
}

export async function recordCommand(dependencies: { firestore: Firestore; now?: () => number }, aquariumId: string, raw: unknown) {
  const { firestore } = dependencies;
  if (!isRecord(raw) || typeof raw.commandId !== 'string' || !ID_PATTERN.test(raw.commandId) || !COMMAND_TYPES.has(String(raw.type))) {
    return { recorded: false, reason: 'malformed' as const };
  }
  const orgId = await aquariumOrg(firestore, aquariumId);
  if (orgId === undefined) return { recorded: false, reason: 'unknown_aquarium' as const };
  const uid = typeof raw.requestedBy === 'string' ? raw.requestedBy : null;
  const ref = firestore.doc(`command_logs/${commandLogId(aquariumId, raw.commandId)}`);
  const now = dependencies.now?.() ?? Date.now();
  try {
    await ref.create({
      aquariumId,
      orgId,
      commandId: raw.commandId,
      type: raw.type,
      state: STATES.has(String(raw.state)) ? raw.state : null,
      durationMs: typeof raw.durationMs === 'number' ? raw.durationMs : null,
      requestedBy: { uid, displayName: uid ? await displayName(firestore, uid) : null },
      requestedAt: typeof raw.requestedAt === 'number' ? raw.requestedAt : now,
      source: 'app',
      status: 'pending' satisfies CommandStatus,
      executedAt: null,
      error: null,
      createdAt: now,
      updatedAt: now,
    });
    return { recorded: true, id: ref.id };
  } catch (error) {
    // Same command written twice (retry): the first entry stands.
    if ((error as { code?: number }).code === 6) return { recorded: false, reason: 'duplicate' as const };
    throw error;
  }
}

export async function recordAck(dependencies: { firestore: Firestore; now?: () => number }, aquariumId: string, raw: unknown) {
  const { firestore } = dependencies;
  if (!isRecord(raw) || typeof raw.commandId !== 'string' || !ID_PATTERN.test(raw.commandId) ||
    (raw.status !== 'done' && raw.status !== 'failed')) {
    return { updated: false, reason: 'malformed' as const };
  }
  const now = dependencies.now?.() ?? Date.now();
  const executedAt = typeof raw.executedAt === 'number' ? raw.executedAt : now;
  const error = typeof raw.error === 'string' ? raw.error.slice(0, 200) : null;
  const ref = firestore.doc(`command_logs/${commandLogId(aquariumId, raw.commandId)}`);
  const orgId = await aquariumOrg(firestore, aquariumId);
  if (orgId === undefined) return { updated: false, reason: 'unknown_aquarium' as const };

  return firestore.runTransaction(async (transaction) => {
    const existing = await transaction.get(ref);
    if (existing.exists) {
      const status = existing.get('status') as CommandStatus;
      if (status === 'done' || status === 'failed') return { updated: false, reason: 'already_final' as const };
      transaction.update(ref, {
        status: raw.status,
        executedAt,
        error,
        ...(status === 'no_response' ? { lateAck: true } : {}),
        updatedAt: now,
      });
      return { updated: true, id: ref.id };
    }
    if (raw.source !== 'schedule' || !COMMAND_TYPES.has(String(raw.type))) {
      return { updated: false, reason: 'unknown_command' as const };
    }
    // A scheduled action the device ran on its own (docs/firmware-changes.md §11).
    transaction.create(ref, {
      aquariumId,
      orgId,
      commandId: raw.commandId,
      type: raw.type,
      state: STATES.has(String(raw.state)) ? raw.state : null,
      durationMs: null,
      requestedBy: { uid: null, displayName: 'Schedule' },
      requestedAt: executedAt,
      source: 'schedule',
      status: raw.status,
      executedAt,
      error,
      createdAt: now,
      updatedAt: now,
    });
    return { updated: true, id: ref.id };
  });
}

/** Scheduled: pending commands older than COMMAND_NO_RESPONSE_MS become no_response. */
export async function markUnansweredCommands(dependencies: { firestore: Firestore; now?: () => number }) {
  const { firestore } = dependencies;
  const now = dependencies.now?.() ?? Date.now();
  const stale = await firestore.collection('command_logs')
    .where('status', '==', 'pending')
    .where('requestedAt', '<', now - COMMAND_NO_RESPONSE_MS)
    .limit(500)
    .get();
  let marked = 0;
  for (const doc of stale.docs) {
    const changed = await firestore.runTransaction(async (transaction) => {
      const fresh = await transaction.get(doc.ref);
      if (fresh.get('status') !== 'pending') return false;
      transaction.update(doc.ref, { status: 'no_response', updatedAt: now });
      return true;
    });
    if (changed) marked += 1;
  }
  return { checked: stale.size, marked };
}
