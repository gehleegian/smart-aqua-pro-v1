// npm run clean:emulator-secrets: delete the emulator-only device credential
// headers that scripts/provision-device.ts writes to firmware/secrets/ (gitignored).
//
//   npm run clean:emulator-secrets                          # removes headers marked "PROJECT: demo-…"
//   npm run clean:emulator-secrets -- --include-unmarked    # also headers from before the marker existed (Sprint 5)
//   npm run clean:emulator-secrets -- --dry-run             # list only
//
// A header for a real project ("PROJECT: practice-smartaqua") is never removed,
// and neither is any file provision-device.ts did not generate. Never prints secrets.
import { readdirSync, readFileSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const dir = path.resolve(root, args.includes('--dir') ? args[args.indexOf('--dir') + 1] : 'firmware/secrets');
const dryRun = args.includes('--dry-run');
const includeUnmarked = args.includes('--include-unmarked');

if (!existsSync(dir)) {
  console.log(`${path.relative(root, dir)} does not exist: nothing to clean.`);
  process.exit(0);
}
const removed = [];
const keptReal = [];
const unmarked = [];
for (const name of readdirSync(dir)) {
  if (!/^SAQ-[A-Z0-9]{4}-[A-Z0-9]{4}\.h$/.test(name)) continue;
  const text = readFileSync(path.join(dir, name), 'utf8');
  if (!text.includes('GENERATED by scripts/provision-device.ts')) continue;
  const project = /^\/\/ PROJECT: (\S+)/m.exec(text)?.[1] ?? null;
  if (project === null) {
    unmarked.push(name);
    if (includeUnmarked) removed.push(name);
  } else if (project.startsWith('demo-')) {
    removed.push(name);
  } else {
    keptReal.push(`${name} (${project})`);
  }
}
for (const name of removed) if (!dryRun) rmSync(path.join(dir, name));
console.log(`${dryRun ? 'Would remove' : 'Removed'} ${removed.length} emulator credential file(s) from ${path.relative(root, dir)}/.`);
if (unmarked.length > 0 && !includeUnmarked) {
  console.log(`${unmarked.length} older file(s) have no PROJECT line (written before Sprint 5). They were kept; re-run with --include-unmarked if none of them belongs to a real device.`);
}
if (keptReal.length > 0) console.log(`Kept ${keptReal.length} file(s) for real projects: ${keptReal.join(', ')}`);
