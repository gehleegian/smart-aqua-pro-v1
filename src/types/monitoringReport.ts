export interface MonitoringReportSummary {
  temperature?: string;
  waterLevel?: string;
  tds?: string;
  ph?: string;
  turbidity?: string;
  ammonia?: string;
  powerStatus?: string;
  equipmentStatus?: string;
}

export interface MonitoringReportDocument {
  report_id: string;
  aquarium_id: string;
  report_type: string;
  start_date: Date;
  end_date: Date;
  summary: string;
  sensor_summary?: MonitoringReportSummary;
  alert_summary?: Record<string, unknown>;
  maintenance_summary?: Record<string, unknown>;
  fileUrl: string | null;
  generated_at: Date;
  generated_by: string;
}

// ---- Sprint 5 (FR21): reports generated by the generateMonitoringReport
// callable and the weekly/monthly schedules. The authoritative shape is
// functions/src/reports/summary.ts (StructuredSummary); this is the part the
// web app reads.
export type ReportType = 'daily' | 'weekly' | 'monthly' | 'custom';

export type ConditionTimes = {
  normal: number;
  warning: number;
  critical: number;
  unavailable: number;
  notMonitored: number;
  notRecorded: number;
  noData: number;
};

export type ReportParameterStats = {
  /** Optional for reports generated before descriptive trends were added. */
  trend?: import('../utils/waterTrends').WaterTrend;
  label: string;
  unit: string | null;
  valid: number;
  invalid: number;
  missing: number;
  unvalidated: number;
  min: number | null;
  max: number | null;
  avg: number | null;
};

export type StructuredReportSummary = {
  version: 1;
  period: { type: ReportType; start: number; end: number; effectiveEnd: number; label: string; timeZone: string };
  aquarium: { id: string; name: string; orgId: string | null; orgName: string | null };
  readings: { rows: number; perParameter: Record<string, ReportParameterStats> };
  completeness: {
    sampleIntervalMs: number;
    expectedSamples: number;
    receivedSamples: number;
    completenessPct: number | null;
    noDataMs: number;
    offlineMs: number;
    offlineEvents: number;
  };
  timeInCondition: { overall: ConditionTimes; perParameter: Record<string, ConditionTimes> };
  alerts: {
    total: number;
    bySeverity: Record<string, number>;
    byParameter: Record<string, { total: number; warning: number; critical: number }>;
    resolved: number;
    stillOpen: number;
    avgResolveMs: number | null;
    longestOpen: { alertId: string; parameter: string; severity: string; type: string | null; durationMs: number; stillOpen: boolean; triggeredAt: number } | null;
  };
  recommendations: {
    generated: number;
    applied: number;
    dismissed: number;
    pending: number;
    autoResolved: number;
    superseded: number;
    actedOnPct: number | null;
    byParameter: Record<string, { generated: number; applied: number; dismissed: number; pending: number }>;
    items: { id: string; createdAt: number; parameter: string; severity: string; title: string; status: string; ruleId: string | null }[];
  };
  maintenance: {
    count: number;
    items: { id: string; performedAt: number; type: string; by: string | null; waterChangePercent: number | null; notes: string | null; recommendationId: string | null }[];
    nextCleaning: { status: string; nextCleaningDue: number | null; due: boolean; reason: string | null; intervalDays: number | null; lastCleanedAt: number | null };
  };
  devices: {
    commands: { total: number; done: number; failed: number; noResponse: number; pending: number; byType: Record<string, number>; bySource: Record<string, number> };
    powerInterruptions: { count: number; totalMs: number; items: { start: number; end: number | null }[] };
  };
  thresholds: {
    status: 'draft' | 'approved';
    speciesId: string | null;
    values: Record<string, { min: number | null; max: number | null; unit: string | null }>;
    missing: string[];
    overridden: string[];
    rules: { total: number; approved: number; draft: number; list: { ruleId: string; parameter: string; severity: string; title: string; status: string; enabled: boolean }[] };
    draftNote: string | null;
  };
};

export type GeneratedReport = {
  id: string;
  aquariumId: string;
  orgId: string | null;
  reportType: ReportType | string;
  periodLabel: string;
  startDate: number | null;
  endDate: number | null;
  generatedAt: number | null;
  generatedBy: string;
  generatedByLabel: string | null;
  summary: string;
  structuredSummary: StructuredReportSummary | null;
  pdfPath: string | null;
  csvPath: string | null;
};
